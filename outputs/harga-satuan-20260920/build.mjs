import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';
const dir = new URL('./', import.meta.url);
const source = await fs.readFile(new URL('../../laundry_app_flutter/lib/shared/default_service_catalog.dart', dir), 'utf8');
const re = /(?:\/\/\s*([^\r\n]+)\s+)?_catalogService\(\s*'([^']*)',\s*'([^']*)',\s*'([^']*)',\s*'([^']*)',\s*'([^']*)',\s*(\d+),\s*(\d+),/g;
const all = [...source.matchAll(re)].map(m=>({source:m[1]??'catalog',id:m[2],category:m[3],item:m[4],variant:m[5],unit:m[6],price:Number(m[7]),sort:Number(m[8])}));
if(all.length !== (source.match(/  _catalogService\(/g)||[]).length) throw Error('Parser omitted services: '+all.length+' '+[...source.matchAll(/_catalogService\(\s*'([^']*)'/g)].filter(m=>!all.some(r=>r.id===m[1])).map(m=>source.slice(m.index-50,m.index+260)).join('\n'));
const rows = all.filter(r=>r.unit!=='KG').sort((a,b)=>a.sort-b.sort);
if(new Set(rows.map(r=>r.id)).size!==rows.length) throw Error('Duplicate IDs');
const wb=Workbook.create();
const sh=wb.worksheets.add('Harga Satuan');
sh.showGridLines=false;
const last=rows.length+7;
sh.getRange(`A1:I${last}`).format.font={name:'Arial',size:11};
sh.getRange('A2').values=[['IDOLA LAUNDRY | DAFTAR HARGA SATUAN']];
sh.getRange('A2').format.font={name:'Arial',size:20,bold:true,color:'#142D59'};
sh.getRange('A3').values=[['Isi kolom kuning Harga Baru (Rp), lalu kirim kembali file ini. Kosong = harga tidak berubah.']];
sh.getRange('A4').values=[['Jangan ubah ID layanan. Harga berupa angka, contoh: 25000. Satuan m² dan pasang tetap dibedakan.']];
sh.getRange('A5').values=[[`Sumber: katalog kode aplikasi, 20 September 2026 • ${rows.length} varian non-KG • Database aktif belum diverifikasi.`]];
sh.getRange('A6').values=[['Catatan: harga lama yang belum terverifikasi dari foto ditandai pada kolom Catatan.']];
sh.getRange('A3:A6').format.font={name:'Arial',size:10,color:'#57667A'};
sh.getRange('A7:I7').values=[['No.','Subkategori','Barang / Layanan','Varian','Satuan','Harga Asal (Rp)','Harga Baru (Rp)','Catatan','ID Layanan']];
const units={PIECE:'buah',ITEM:'item',PAIR:'pasang',M2:'m²',PCS:'buah'};
const values=rows.map((r,i)=>[i+1,r.category,r.item,r.variant,units[r.unit]??r.unit,r.price,null,r.source.startsWith('existing')?'Harga lama; belum terverifikasi foto':'',r.id]);
sh.getRange(`A8:I${last}`).values=values;
sh.tables.add(`A7:I${last}`,true,'HargaSatuan');
sh.getRange('A7:I7').format.fill='#142D59';
sh.getRange('A7:I7').format.font={name:'Arial',size:11,bold:true,color:'#FFFFFF'};
const widths={A:6,B:24,C:32,D:24,E:10,F:18,G:18,H:33,I:57};
for(const [c,w] of Object.entries(widths)) sh.getRange(`${c}:${c}`).format.columnWidth=w;
sh.getRange(`A7:I${last}`).format.wrapText=true;
sh.getRange(`A7:I${last}`).format.rowHeight=34;
sh.getRange(`A7:I${last}`).format.verticalAlignment='center';
sh.getRange('A2:I2').format.rowHeight=32;
sh.getRange('A3:I6').format.rowHeight=21;
sh.getRange(`F8:G${last}`).setNumberFormat('#,##0');
sh.getRange(`G8:G${last}`).format.fill='#FFF0BD';
sh.getRange(`G8:G${last}`).format.font={name:'Arial',size:11,color:'#915E00',bold:true};
sh.freezePanes.freezeRows(7);
wb.recalculate();
const actual=sh.getRange(`A8:I${last}`).values;
if(actual.length!==rows.length||actual.some((r,i)=>r[5]!==rows[i].price||r[8]!==rows[i].id))throw Error('Verification failed');
if(actual.flat().some(v=>typeof v==='string'&&/^#(REF!|VALUE!|DIV\/0!|NAME\?|N\/A)/.test(v))) throw Error('Cell error');
console.log(JSON.stringify({services:all.length,nonKg:rows.length,categories:[...new Set(rows.map(r=>r.category))]}));
console.log((await wb.inspect({kind:'table',range:'\'Harga Satuan\'!A7:H11',include:'values,formulas',tableMaxRows:5,tableMaxCols:8})).ndjson);
const preview=await wb.render({sheetName:'Harga Satuan',range:'A1:H15',scale:1,format:'png'});
await fs.writeFile(new URL('preview.png',dir),new Uint8Array(await preview.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(wb)).save(fileURLToPath(new URL('Harga Satuan Idola Laundry.xlsx',dir)));
